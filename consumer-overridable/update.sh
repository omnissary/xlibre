get_version() {
  curl -SL "https://api.github.com/repos/X11Libre/$1/tags" | jq -r '.[].name' | grep "$2" | sed -e "s/^.*$2-//" | sort -rn | head -1
}

get_sha256() {
  nix --extra-experimental-features nix-command store prefetch-file --json "https://github.com/X11Libre/$1/archive/refs/tags/$2-$3.tar.gz" | jq -r .hash
}
get_source() {
  VERSION="$(get_version "$1" "$2")"
  cat <<EOF
    $1 = {
      version = "$VERSION";
      url = "https://github.com/X11Libre/$1/archive/refs/tags/$2-$VERSION.tar.gz";
      sha256 = "$(get_sha256 "$1" "$2" "$VERSION")";
    };
EOF
}

