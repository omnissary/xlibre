#!/usr/bin/env nix
#! nix shell nixpkgs#bash nixpkgs#curl nixpkgs#jq nixpkgs#nix nixpkgs#gnused nixpkgs#gnugrep nixpkgs#git nixpkgs#miller --command bash

#https://nixos.org/manual/nix/stable/command-ref/new-cli/nix.html?highlight=shebang#shebang-interpreter

set -euo pipefail

# These two files will be overwritten by this script
SOURCE_FILE="consumer-overridable/fetchurl-sources.nix"
JSON_FILE="sources-info.json"
PIN_FILE="pin.json"

SOURCE_FILE_INTERMEDIATE_ARRAY=()
JSON_FILE_INTERMEDIATE=""

REPOS=()
PREFIXES=()
VERSIONS=()
UPDATED_INDEXES=()

get_version() {
  # https://stackoverflow.com/questions/4493205/unix-sort-of-version-numbers
  #  use "sort -rV"
  #  or use "sort -t. -k 1,1nr -k 2,2nr -k 3,3nr -k 4,4nr"
  curl -sSL "https://api.github.com/repos/X11Libre/$1/tags" | jq -r '.[].name' | grep "$2" | sed -e "s/^.*$2-//" |
    sort -t. -k 1,1nr -k 2,2nr -k 3,3nr -k 4,4nr |
    head -1
}

get_sha256() {
  nix --extra-experimental-features nix-command store prefetch-file --json "https://github.com/X11Libre/$1/archive/refs/tags/$2-$3.tar.gz" | jq -r .hash
}

get_source_pre() {
  REPO="$1"
  PREFIX="$2"
  VERSION_GET=""

  # get VERSION from pin file
  for ((j = 0; j < "$(jq "length" "$PIN_FILE")"; j++)); do
    if [ "$REPO" = "$(jq -r ".[$j].REPO" "$PIN_FILE")" ]; then
      VERSION_GET="$(jq -r ".[$j].VERSION" "$PIN_FILE")"
    fi
  done
  if [ "$VERSION_GET" = "" ]; then
    VERSION_GET="$(get_version "$REPO" "$PREFIX")"
  fi

  REPOS+=("$REPO")
  PREFIXES+=("$PREFIX")
  VERSIONS+=("$VERSION_GET")

  if [ "$3" != "$VERSION_GET" ]; then
    UPDATED_INDEXES+=("$4")
  fi
}

get_source() {
  REPO="$1"
  PREFIX="$2"
  VERSION_GET="$3"
  SHA256=""

  # get SHA256 from pin file
  for ((j = 0; j < "$(jq "length" "$PIN_FILE")"; j++)); do
    if [ "$REPO" = "$(jq -r ".[$j].REPO" "$PIN_FILE")" ]; then
      SHA256="$(jq -r ".[$j].SHA256" "$PIN_FILE")"
    fi
  done
  if [ "$SHA256" = "" ]; then
    SHA256="$(get_sha256 "$REPO" "$PREFIX" "$VERSION_GET")"
  fi

  cat <<EOF
    ${REPO} = {
      version = "${VERSION_GET}";
      url = "https://github.com/X11Libre/${REPO}/archive/refs/tags/${PREFIX}-${VERSION_GET}.tar.gz";
      sha256 = "${SHA256}";
    };
EOF
}

for ((i = 0; i < "$(jq "length" "$JSON_FILE")"; i++)); do
  # progress message:
  printf "[%s/%s]: Checking %s..." "$(("$i" + 1))" "$(jq 'length' "$JSON_FILE")" "$(jq -r ".[$i].REPO" "$JSON_FILE")"
  if [ "$i" -ne 0 ]; then
    # Prevent github API rate limit exceed
    sleep 10
  fi

  if [ "$i" -eq 0 ]; then
    SOURCE_FILE_INTERMEDIATE_ARRAY+=("$(
      cat <<EOF
# Auto generated by update-sources.sh
{
  xlibre = {
    # xserver
EOF
    )")
  fi
  # UPDATED_INDEXES array cannot be inside subshell
  get_source_pre "$(jq -r ".[$i].REPO" "$JSON_FILE")" "$(jq -r ".[$i].PREFIX" "$JSON_FILE")" "$(jq -r ".[$i].VERSION" "$JSON_FILE")" "$i"

  # SOURCE_FILE_INTERMEDIATE_ARRAY+=("$(get_source "$(jq -r ".[$i].REPO" "$JSON_FILE")" "$(jq -r ".[$i].PREFIX" "$JSON_FILE")" "$(jq -r ".[$i].VERSION" "$JSON_FILE")" "$i")")
  SOURCE_FILE_INTERMEDIATE_ARRAY+=("$(get_source "$REPO" "$PREFIX" "$VERSION_GET")")

  if [ "$i" -eq 0 ]; then
    SOURCE_FILE_INTERMEDIATE_ARRAY+=("$(
      cat <<EOF

    # drivers
EOF
    )")
  fi
done

SOURCE_FILE_INTERMEDIATE_ARRAY+=("$(
  cat <<EOF
  };
}
EOF
)")

if [ ${#UPDATED_INDEXES[@]} -eq 0 ]; then
  printf "\n%s\n" "No packages are updated."
else
  # Generating commit message before overwriting "$JSON_FILE"
  COMMIT_MESSAGE="$(
    printf "\n%s\n" "Updated package(s):"
    for i in "${UPDATED_INDEXES[@]}"; do
      PREFIX="$(jq -r ".[$i].PREFIX" "$JSON_FILE")"
      OLD_VERSION="$(jq -r ".[$i].VERSION" "$JSON_FILE")"
      NEW_VERSION="${VERSIONS[$i]}"
      printf "%s: %s -> %s\n" "$PREFIX" "$OLD_VERSION" "$NEW_VERSION"
    done
  )"

  JSON_FILE_INTERMEDIATE="$(
    {
      echo "REPO,PREFIX,VERSION"
      for ((i = 0; i < "$(jq "length" "$JSON_FILE")"; i++)); do
        echo "${REPOS[$i]},${PREFIXES[$i]},${VERSIONS[$i]}"
      done
    } | mlr --icsv --ojson cat | jq
  )"

  # Overwrite files
  printf "%s\n" "${SOURCE_FILE_INTERMEDIATE_ARRAY[@]}" >"$SOURCE_FILE"
  printf "%s\n" "$JSON_FILE_INTERMEDIATE" >"$JSON_FILE"

  # git
  git add "$SOURCE_FILE" "$JSON_FILE"
  TZ=UTC git commit -m "$COMMIT_MESSAGE"
fi
