REPOS=()
PREFIXES=()
VERSIONS=()
UPDATED_INDEXES=()

get_version() {
  curl -sSL "https://api.github.com/repos/X11Libre/$1/tags" | jq -r '.[].name' | grep "$2" | sed -e "s/^.*$2-//" | sort -rn | head -1
}

get_sha256() {
  nix --extra-experimental-features nix-command store prefetch-file --json "https://github.com/X11Libre/$1/archive/refs/tags/$2-$3.tar.gz" | jq -r .hash
}

get_source_pre() {
  REPO="$1"
  PREFIX="$2"
  VERSION_GET="$(get_version "$REPO" "$PREFIX")"

  REPOS+=("$REPO")
  PREFIXES+=("$PREFIX")
  VERSIONS+=("$VERSION_GET")

  if [ "$3" != "$VERSION_GET" ]; then
    UPDATED_INDEXES+=("$4")
  fi
}

get_source() {
  cat <<EOF
    $1 = {
      version = "$3";
      url = "https://github.com/X11Libre/$1/archive/refs/tags/$2-$3.tar.gz";
      sha256 = "$(get_sha256 "$1" "$2" "$3")";
    };
EOF
}

for ((i = 0; i < "$(jq "length" "$JSON_FILE")"; i++)); do
  # progress message:
